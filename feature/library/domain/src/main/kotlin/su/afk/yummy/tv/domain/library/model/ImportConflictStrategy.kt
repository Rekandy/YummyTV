package su.afk.yummy.tv.domain.library.model

/** Стратегия обработки конфликтов при импорте записи, которая уже есть в локальной библиотеке. */
enum class ImportConflictStrategy {
    /** Обновить статус и оценку существующего тайтла данными из файла. */
    UPDATE,

    /** Пропустить конфликтующий тайтл, сохранив текущие локальные данные. */
    SKIP,
}
